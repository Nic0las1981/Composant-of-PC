/** One scene unit equals 125 mm. +X is the open side, +Y up, +Z the front.
 * These are modeled product envelopes and appearance cues, not manufacturer CAD
 * files. Fine geometry, cable routing, connectors and mounting tolerances remain
 * illustrative. Compatibility is calculated separately from the catalog specs.
 */
export const MM = 0.008;

interface BaseVisualProfile {
  id: string;
  name: string;
  category: CategoryId;
  color: string;
  accent: string;
  rgb: boolean;
  /** Schematic envelopes are display-only and are never manufacturer specs. */
  fidelity?: "reconstructed" | "schematic";
}

export interface CaseVisualProfile extends BaseVisualProfile {
  category: "case";
  kind: "panoramic" | "airflow" | "compact" | "sandwich" | "wood-front";
  widthMm: number;
  heightMm: number;
  depthMm: number;
  fanCount: number;
  fanSizeMm: number;
  fanRgb: boolean;
  frameColor: string;
  frontColor: string;
  glass: boolean;
  woodAccent: boolean;
  stockFanMount?: "front" | "side" | "rear" | "none";
  rearFanCount?: number;
  sidePanel: "glass" | "acrylic" | "vented";
}
export interface GpuVisualProfile extends BaseVisualProfile {
  category: "gpu";
  lengthMm: number;
  heightMm: number;
  thicknessMm: number;
  fanCount: number;
  fanSizeMm: number;
  shroudColor: string;
  backplateColor: string;
  fanLayout?: "inline" | "flow-through";
  /** RGB fan halos are distinct from a card with only an illuminated logo. */
  fanRgb?: boolean;
}
export interface CoolerVisualProfile extends BaseVisualProfile {
  category: "cooler";
  kind: "dual-tower" | "low-profile" | "aio";
  radiatorSizeMm?: 120 | 240 | 280 | 360 | 420;
  radiatorThicknessMm?: number;
  radiatorLengthMm?: number;
  radiatorWidthMm?: number;
  tubeColor?: string;
  pumpColor?: string;
  fanRgb?: boolean;
  pumpDisplay?: "lcd" | "rgb-ring" | "logo";
  heightMm: number;
  widthMm: number;
  depthMm: number;
  fanCount: number;
  fanSizeMm: number;
  finColor: string;
  fanColor: string;
  heatpipes: number;
}
export interface RamVisualProfile extends BaseVisualProfile {
  category: "ram";
  heightMm: number;
  lengthMm: number;
  thicknessMm: number;
  sticks: number;
  heatspreaderColor: string;
}
export interface BoardVisualProfile extends BaseVisualProfile {
  category: "motherboard";
  heightMm: number;
  widthMm: number;
  slots: number;
  pcbColor: string;
  heatsinkColor: string;
  formFactor: FormFactor;
}
export interface PsuVisualProfile extends BaseVisualProfile {
  category: "psu";
  widthMm: number;
  heightMm: number;
  depthMm: number;
  fanSizeMm: number;
  format: "ATX" | "SFX";
}
export interface CpuVisualProfile extends BaseVisualProfile {
  category: "cpu";
  widthMm: number;
  heightMm: number;
  depthMm: number;
  socket: Socket;
}
export interface StorageVisualProfile extends BaseVisualProfile {
  category: "storage";
  widthMm: number;
  lengthMm: number;
  heightMm: number;
  labelColor: string;
  hasHeatsink: boolean;
}
export type VisualProfile =
  | CaseVisualProfile
  | GpuVisualProfile
  | CoolerVisualProfile
  | RamVisualProfile
  | BoardVisualProfile
  | PsuVisualProfile
  | CpuVisualProfile
  | StorageVisualProfile;

