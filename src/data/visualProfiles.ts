  lookup(psuProfiles, component);
export const getCpuProfile = (component?: ProfileInput) =>
  lookup(cpuProfiles, component);
export const getStorageProfile = (component?: ProfileInput) =>
  lookup(storageProfiles, component);
export const getVisualProfile = (component?: ProfileInput) =>
  lookup(visualProfiles, component);
