"""Build the compact runtime offer refresh from retained primary observations."""
import json
from pathlib import Path
from collections import Counter
ROOT=Path(__file__).resolve().parents[1]
path=ROOT/'data/deep-review/prices/observations.jsonl'
records={};counts=Counter()
for line in path.read_text().splitlines() if path.exists() else []:
    row=json.loads(line);counts[(row['retailer'],row['status'])]+=1
    matches=[p for p in row['pages'] if p.get('match') and p.get('httpStatus')==200]
    if not matches:continue
    key=(row['componentId'],row['mpn'])
    record=records.setdefault(key,{'mpn':row['mpn'],'checkedURLs':[],'offers':[],'sources':[]})
    for page in matches:
        url=page['url']
        record['checkedURLs']=list(dict.fromkeys(record['checkedURLs']+[url]))
        record['offers']=[o for o in record['offers'] if o['url']!=url]
        record['offers'] += [o for o in row['offers'] if o['url']==url]
        record['sources']=[s for s in record['sources'] if s['url']!=url]
        record['sources'].append({'name':row['retailer']+' — offre contrôlée','url':url,'checkedAt':page['checkedAt'],'kind':'retailer'})
products={}
for (id,mpn),record in records.items(): products.setdefault(id,[]).append(record)
target=ROOT/'src/data/deepPriceCatalog.ts'
target.write_text('// Generated by scripts/build-deep-price-catalog.py from exact primary-product observations.\nimport type {VerifiedOffer,VerifiedSource} from "./verifiedTypes.ts";\nexport interface DeepPriceRecord {mpn:string;checkedURLs:string[];offers:VerifiedOffer[];sources:VerifiedSource[]}\nexport const deepPriceRecords:Record<string,DeepPriceRecord[]> = '+json.dumps(products,ensure_ascii=False,indent=2)+';\n')
summary={'referenceRecords':len(records),'observedOffers':sum(len(r['offers']) for r in records.values()),'outcomes':[{'retailer':r,'status':s,'count':n} for (r,s),n in sorted(counts.items())]}
(ROOT/'data/deep-review/prices/summary.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(summary,ensure_ascii=False))
