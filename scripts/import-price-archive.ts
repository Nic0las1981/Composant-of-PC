/** Build dated USD reference amounts from the immutable catalogue archive.
 * These amounts never feed the EUR budget or claim a current merchant offer.
 * Usage: npx tsx scripts/import-price-archive.ts [--check] [--source-dir PATH]
 */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, rename, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

type SourceType = "memory" | "internal-hard-drive" | "video-card" | "motherboard" | "power-supply";
type RawRecord = Record<string, unknown> & { price: number | null };
interface SourceRow {
  id: string;
  sourceType: SourceType;
  sourceIndex: number;
  recordKey: string;
  recordHash: string;
  record: RawRecord;
}
interface Snapshot {
  schemaVersion: number;
  source: {
    repository: string;
    commit: string;
    sourceUpdated: string;
    files: Record<string, { sha256: string; rows: number; url: string }>;
  };
  selection: {
    counts: Record<SourceType, number>;
    baselineIds: string[];
    legacyIds: string[];
  };
  records: SourceRow[];
}

const root = fileURLToPath(new URL("../", import.meta.url));
const snapshot = JSON.parse(await readFile(resolve(root, "data/catalog-source.json"), "utf8")) as Snapshot;
const hash = (value: string | Buffer) => createHash("sha256").update(value).digest("hex");
function canonical(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value !== null && typeof value === "object") {
    return `{${Object.entries(value).sort(([a], [b]) => a.localeCompare(b, "en")).map(([key, item]) => `${JSON.stringify(key)}:${canonical(item)}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

assert.equal(snapshot.schemaVersion, 2);
assert.equal(snapshot.source.repository, "https://github.com/docyx/pc-part-dataset");
assert.match(snapshot.source.commit, /^[a-f0-9]{40}$/);
// A different source date must be reviewed with the UI/type contract instead
// of silently turning an old observation into a supposedly recent offer.
assert.equal(snapshot.source.sourceUpdated, "2025-07-23");
const sourceTypes: SourceType[] = ["memory", "internal-hard-drive", "video-card", "motherboard", "power-supply"];
const ids = new Set<string>();
const keys = new Set<string>();
const counts: Record<string, number> = {};
for (const row of snapshot.records) {
  assert(sourceTypes.includes(row.sourceType), `Unsupported source type: ${row.sourceType}`);
  assert(!ids.has(row.id) && !snapshot.selection.baselineIds.includes(row.id), `Duplicate id: ${row.id}`);
  assert(!keys.has(`${row.sourceType}:${row.recordKey}`), `Duplicate reference: ${row.id}`);
  assert(row.id.endsWith(`-${hash(row.recordKey).slice(0, 12)}`), `Unstable reference id: ${row.id}`);
  assert.equal(hash(canonical(row.record)), row.recordHash, `Record checksum failed: ${row.id}`);
  const file = snapshot.source.files[`${row.sourceType}.json`];
  assert(file && Number.isInteger(row.sourceIndex) && row.sourceIndex >= 0 && row.sourceIndex < file.rows, `Invalid source index: ${row.id}`);
  assert(row.record.price === null || typeof row.record.price === "number" && Number.isFinite(row.record.price), `Invalid price field: ${row.id}`);
  ids.add(row.id);
  keys.add(`${row.sourceType}:${row.recordKey}`);
  counts[row.sourceType] = (counts[row.sourceType] ?? 0) + 1;
}
assert.deepEqual(counts, snapshot.selection.counts);
assert(snapshot.selection.legacyIds.every(id => ids.has(id)), "All previously imported IDs must remain available");

const args = process.argv.slice(2);
const sourceDirIndex = args.indexOf("--source-dir");
if (sourceDirIndex !== -1) {
  const directory = args[sourceDirIndex + 1];
  assert(directory, "--source-dir requires a directory");
  for (const type of sourceTypes) {
    const filename = `${type}.json`;
    const contents = await readFile(resolve(directory, filename));
    assert.equal(hash(contents), snapshot.source.files[filename].sha256, `Upstream file checksum failed: ${filename}`);
    const records = JSON.parse(contents.toString("utf8")) as RawRecord[];
    for (const row of snapshot.records.filter(row => row.sourceType === type)) {
      assert.equal(hash(canonical(records[row.sourceIndex])), row.recordHash, `Source row mismatch: ${row.id}`);
    }
  }
}

const priced = snapshot.records.filter(row => typeof row.record.price === "number" && row.record.price > 0);
const records = priced.map(row => `  ${JSON.stringify(row.id)}: ${JSON.stringify({
  amount: row.record.price,
  rowId: `${row.sourceType}:${row.sourceIndex}-${row.recordHash.slice(0, 12)}`,
  sourceType: row.sourceType,
})},`).join("\n");
const output = `// Generated by scripts/import-price-archive.ts from an immutable public archive.\n// Historical USD reference amounts, never current offers or EUR budget prices.\n// Source data: docyx/pc-part-dataset, MIT, Copyright (c) 2021-2025 Doc Oliver.\n\nexport const PRICE_ARCHIVE_SOURCE = ${JSON.stringify({
  name: "docyx/pc-part-dataset", repository: snapshot.source.repository,
  snapshot: snapshot.source.commit, snapshotDate: snapshot.source.sourceUpdated,
  market: "US", currency: "USD",
})} as const;\n\nexport interface ArchivedPriceEntry {\n  readonly amount: number;\n  readonly rowId: string;\n  readonly sourceType: "memory" | "internal-hard-drive" | "video-card" | "motherboard" | "power-supply";\n}\n\nexport const catalogPriceArchive: Readonly<Record<string, ArchivedPriceEntry>> = {\n${records}\n};\n`;
const destination = resolve(root, "src/data/catalogPriceArchive.ts");
if (args.includes("--check")) {
  assert.equal(await readFile(destination, "utf8"), output, "Generated price archive is stale; run npx tsx scripts/import-price-archive.ts");
} else {
  await writeFile(`${destination}.tmp`, output);
  await rename(`${destination}.tmp`, destination);
}
console.log(`${args.includes("--check") ? "Verified" : "Generated"} ${priced.length} historical USD amounts from archive ${snapshot.source.sourceUpdated}; EUR budget prices unchanged.`);
